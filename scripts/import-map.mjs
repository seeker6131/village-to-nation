// v0.27 Map Maker file (.v2nmap.json) -> game map module (src/maps/<id>.js) + registry (src/maps/index.js).
// Usage: node scripts/import-map.mjs maps/map1.v2nmap.json map1 "แมพแบบ 1"
// What becomes what:
//   ground: grass/lawn/forest -> g, meadow -> m, rocky/cliff -> r, dirt/soil/sand-ish paths -> d, farm -> f, sand -> s,
//           water -> w, sea/deep -> S (sea: sandy beach shore)          roads: any road type -> lane tile (main* -> main)
//   trees: tree objects -> choppable tree nodes with the exact sprite; stumps -> stump nodes
//   markers: spawn -> player start, npc -> NPC house plots (tier 1), lot -> house lots for players, public -> public plots
//   objects: the leader house fixes the village origin; workshop (bz_work) -> the workshop slot; others -> solid props
import fs from 'node:fs';
const [, , file, id = 'map1', th = 'แมพจากแอปสร้างแมพ'] = process.argv;
const f = JSON.parse(fs.readFileSync(file, 'utf8'));
if (f.format !== 'v2n-map@1') throw new Error('not a v2n-map@1 file');
if (f.width !== 144 || f.height !== 96) console.warn('⚠️ the game world is 144x96; the map is cropped/padded');
const W = 144, H = 96;
const GMAP = { grass: 'g', lawn: 'g', forest: 'g', meadow: 'm', rocky: 'r', cliff: 'r', dirt: 'd', soil: 'd', farm: 'f', sand: 's', water: 'w', sea: 'S', deep: 'S' };
const gk = f.groundKey, rk = f.roadKey;
const ground = [], roads = [];
for (let y = 0; y < H; y++) {
  let g = '', r = '';
  for (let x = 0; x < W; x++) {
    const tid = gk[f.groundRows[y]?.[x]] || 'grass'; g += GMAP[tid] || 'g';
    const rid = rk[f.roadRows[y]?.[x]] || 'none'; r += rid === 'none' ? '.' : /^main/.test(rid) ? 'M' : /^plaza/.test(rid) ? 'P' : 'L';
  }
  ground.push(g); roads.push(r);
}
const assets = Object.fromEntries(f.assets.map(a => [a.id, a]));
const sprite = o => (assets[o.asset]?.src || '').replace(/^game:/, '');
const trees = [], props = [], warn = [];
let leader = null, workshop = null;
for (const o of f.objects) {
  const sp = sprite(o), a = assets[o.asset];
  if (a?.kind === 'tree') { trees.push([o.x, o.y + o.fh - 1, sp]); continue; }
  if (/^leader_/.test(sp)) { leader = { tx: o.x, ty: o.y }; continue; }
  if (/^bz_work/.test(sp) && !workshop && (o.tier || 1) <= 2) { workshop = { tx: o.x + Math.floor((o.fw - 4) / 2), ty: o.y + o.fh - 3 }; continue; }
  if (!sp || sp.startsWith('data:')) { warn.push(`imported image "${a?.name}" skipped (copy it into source_art first)`); continue; }
  props.push({ tier: o.tier || 1, name: sp, x: o.x, y: o.y, fw: o.fw, fh: o.fh, flip: !!o.flip, rot: o.rot || 0, ...(a?.kind === 'bridge' ? { bridge: true } : {}), scale: a?.pw && o.tw ? Math.round(o.tw * 16 / a.pw * 100) / 100 : 1, label: o.label || a?.name || '' });
}
if (!leader) throw new Error('the map needs a leader house (บ้านผู้นำ) — it marks where the village is');
const mk = t => f.markers.filter(m => m.type === t);
const spawn = mk('spawn')[0] ? { x: mk('spawn')[0].x, y: mk('spawn')[0].y } : null;
// a house plot is 4x3; put it in the middle of the marked box, against its bottom edge (front yard / lane below)
const tierRows = f.tierRows || null, tierOf = (x, y) => Math.max(1, Math.min(5, +(tierRows?.[Math.floor(y)]?.[Math.floor(x)]) || 1));
const plot = m => ({ tx: m.x + Math.max(0, Math.floor((m.w - 4) / 2)), ty: m.y + Math.max(0, m.h - 3 - (m.h >= 5 ? 1 : 0)), tier: m.tier || tierOf(m.x + m.w / 2, m.y + m.h - 1) });
const npcSlots = mk('npc').map(plot), lots = mk('lot').map(plot);
// building plots: the four village plots in order (home, farm, market, hall); typed plots from the Map Maker v2 keep their type
const ORDER = ['home', 'farm', 'market', 'hall'], pubs = mk('public');
const publics = ORDER.map((id, k) => pubs.find(m => m.plot === id) || pubs.filter(m => !m.plot)[k]).map(m => m && { x: m.x, y: m.y, w: m.w, h: m.h, label: m.label, plot: m.plot || null });
const cityPlots = pubs.filter(m => m.plot && !ORDER.includes(m.plot)).map(m => ({ plot: m.plot, x: m.x, y: m.y, w: m.w, h: m.h, label: m.label }));
const out = `// GENERATED by scripts/import-map.mjs from ${file.split('/').pop()} (${f.saved || ''}) — do not edit by hand, re-import instead.
export const MAP = ${JSON.stringify({ id, th, w: W, h: H, leader, workshop, spawn, npcSlots, lots, publics, cityPlots, props, trees, ground, roads, heightRows: f.heightRows?.map(r => r.slice(0, W).padEnd(W, '0')) || null, stairRows: f.stairRows?.map(r => r.slice(0, W).padEnd(W, '.')) || null, tiers: tierRows ? tierRows.map(r => r.slice(0, W).padEnd(W, '1')) : null }, null, 0)};
`;
fs.writeFileSync(`src/maps/${id}.js`, out);
const ids = fs.readdirSync('src/maps').filter(n => /^map\d+\.js$/.test(n) || /^fantasy_[a-z]+\.js$/.test(n)).map(n => n.slice(0, -3)).sort();
if (!fs.existsSync('src/maps/mapArt.js')) fs.writeFileSync('src/maps/mapArt.js', '// GENERATED by scripts/plan-map.mjs\nexport const MAP_ART = {};\n');
fs.writeFileSync('src/maps/index.js', `// GENERATED by scripts/import-map.mjs — maps drawn in the Map Maker (editor/index.html)\nimport { ART10 } from '../artManifest.js';\nimport { MAP_ART } from './mapArt.js';\n${ids.map(i => `import { MAP as ${i} } from './${i}.js';`).join('\n')}\nfor (const [k, v] of Object.entries(MAP_ART)) if (!ART10[k]) ART10[k] = v; // sprites made from images imported into the Map Maker\nexport const MAPS = [${ids.join(', ')}];\n`);
console.log(`${id}: ${trees.length} trees, ${props.length} props, ${npcSlots.length} NPC plots, ${lots.length} lots, leader at ${leader.tx},${leader.ty}${workshop ? `, workshop ${workshop.tx},${workshop.ty}` : ''}`);
for (const w of warn) console.log('⚠️', w);
