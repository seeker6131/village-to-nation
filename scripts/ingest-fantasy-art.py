#!/usr/bin/env python3
"""Crop GPT magenta-backed 3-column fantasy building sheets into 3 transparent tiers.
Downsample nearest 1/4, retain hard pixels and 1px outlines. No ground base is added.
Source PNGs remain unmodified. Output is WEBP lossless with alpha and a generated ES manifest.
"""
from PIL import Image
import numpy as np
from pathlib import Path
import json,sys,math
R=Path(__file__).resolve().parent.parent
SRC=R/'source_art'/'fantasy';OUT=R/'assets'/'fantasy';OUT.mkdir(parents=True,exist_ok=True)
BUILDINGS=['castle','house_a','house_b','house_c','dorm','inn','town_hall','barracks','bank','market','merchant_guild','blacksmith','lumber_mill','fishing']
# The first six are mandatory for phase 4, the remaining are prepared for the new economy.

def transparent(im):
 im=im.convert('RGBA')
 p=im.load();w,h=im.size
 for y in range(h):
  for x in range(w):
   r,g,b,a=p[x,y]
   if r>170 and b>140 and g<125 and r>g*1.5 and b>g*1.35: p[x,y]=(0,0,0,0)
   elif a<128: p[x,y]=(0,0,0,0)
   else: p[x,y]=(r,g,b,255)
 return im

def down(c):
 return c.resize((max(1,round(c.width/4)),max(1,round(c.height/4))),Image.Resampling.NEAREST)

def clean_crop(c):
 b=c.getchannel('A').getbbox()
 if not b:return c
 x0,y0,x1,y1=b
 pad=1
 return c.crop((max(0,x0-pad),max(0,y0-pad),min(c.width,x1+pad),min(c.height,y1+pad)))

def store(name,c,already_down=False):
 c=clean_crop(transparent(c if already_down else down(c)))
 c.save(OUT/(name+'.webp'),'WEBP',lossless=True,method=5)
 return [c.width,c.height]

def main():
 man={}
 for f in BUILDINGS:
  file=SRC/(f+'.png')
  if not file.exists():continue
  im=down(Image.open(file).convert('RGB'));w,h=im.size
  # GPT does not center each drawing within the nominal 1/3 cell. The next tier may overhang
  # into that cell. Detect low-ink vertical boundaries in a broad neighbourhood of each third.
  arr=np.asarray(im).astype(np.int16);r,g,b=arr[...,0],arr[...,1],arr[...,2]
  solid=~((r>170)&(b>140)&(g<125)&(r>g*1.5)&(b>g*1.35))
  ink=solid.sum(axis=0)
  separators=[0]
  for j in (1,2):
   nominal=round(j*w/3)
   lo=max(separators[-1]+40,nominal-round(w*.11));hi=min(w-40,nominal+round(w*.03))
   values=[(int(ink[max(0,x-3):min(w,x+4)].sum()),abs(x-nominal),x) for x in range(lo,hi)]
   separators.append(min(values)[2])
  separators.append(w)
  man[f]=[]
  for i in range(3):
   piece=im.crop((separators[i],0,separators[i+1],h))
   man[f].append(store(f'{f}_{i+1}',piece,already_down=True))
 # 16 stair sprites (4x4) on magenta, to be drawn on terrain as walkable connector.
 stairs=Image.open(SRC/'cliff_stairs.png').convert('RGB');w,h=stairs.size
 man['cliff_stairs']=[]
 for j in range(4):
  for i in range(4):
   piece=stairs.crop((round(i*w/4),round(j*h/4),round((i+1)*w/4),round((j+1)*h/4)))
   man['cliff_stairs'].append(store(f'cliff_stairs_{j*4+i}',piece))
 # Interior walls include their own black outside region; keep solid black, nearest shrunk for performance.
 for name in ['int_hunter','int_fish','int_tailor']:
  file=SRC/(name+'.png')
  if file.exists():
   im=Image.open(file).convert('RGB');c=down(im)
   c.save(OUT/(name+'.webp'),'WEBP',lossless=True,method=5)
   man[name]=[c.width,c.height]
 lines=['// Generated by scripts/ingest-fantasy-art.py; sizes are 4x nearest and include no ground.',
        'export const FANTASY_BUILDINGS = '+json.dumps({k:v for k,v in man.items() if k not in ['cliff_stairs','int_hunter','int_fish','int_tailor']})+';',
        'export const FANTASY_STAIRS = '+json.dumps(man['cliff_stairs'])+';',
        'export const FANTASY_INTERIORS = '+json.dumps({k:v for k,v in man.items() if k.startswith('int_')})+';',
        'export const FANTASY_ASSET_NAMES = '+json.dumps([f'fantasy/{f}_{i+1}' for f in BUILDINGS if f in man for i in range(3)]+[f'fantasy/cliff_stairs_{i}' for i in range(16)]+[f'fantasy/{name}' for name in ['int_hunter','int_fish','int_tailor'] if name in man])+';']
 (R/'src'/'fantasyManifest.js').write_text('\n'.join(lines)+'\n',encoding='utf-8')
 print('Fantasy art:',len(man),'families,',sum(1 for p in OUT.iterdir() if p.suffix=='.webp'),'WebP assets')
if __name__=='__main__':main()
