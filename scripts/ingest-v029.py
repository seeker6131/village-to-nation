#!/usr/bin/env python3
"""v0.29 art: front-door paths (stone / concrete, 8 each) and era bridges (log / stone / concrete, horizontal + vertical).

source_art/v029/*.png (GPT sheets on magenta) -> assets/v10/<name>.webp (2x) + entries in src/maps/mapArt.js
(merged into ART10 by src/maps/index.js).   python3 scripts/ingest-v029.py [--preview]
"""
import json, os, re, sys
import numpy as np, cv2
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, OUT = os.path.join(ROOT, 'source_art', 'v029'), os.path.join(ROOT, 'assets', 'v10')
ART_JS = os.path.join(ROOT, 'src', 'maps', 'mapArt.js')

def key(path):
    a = np.array(Image.open(path).convert('RGB')).astype(np.int32)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    bg = (r > 150) & (b > 150) & (g < 120) & (np.abs(r - b) < 90)
    m = (~bg).astype(np.uint8)
    m = cv2.morphologyEx(m, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))
    for _ in range(2):  # magenta halo on the edge
        edge = (m == 1) & (cv2.dilate((m == 0).astype(np.uint8), np.ones((3, 3), np.uint8)) == 1)
        pink = (r > 120) & (b > 90) & (g < r - 45) & (b > g + 30)
        m[edge & pink] = 0
    return a.astype(np.uint8), m

def pieces(path, gap):
    a, m = key(path)
    n, lab, st, _ = cv2.connectedComponentsWithStats(m, connectivity=8)
    boxes = [list(st[i][:4]) + [i] for i in range(1, n) if st[i][4] >= 30]
    # merge boxes closer than `gap` (pebbles / grass tufts / lamp posts belong to their piece)
    groups = [[b] for b in boxes]
    changed = True
    while changed:
        changed = False
        for i in range(len(groups)):
            for j in range(i + 1, len(groups)):
                bi, bj = bb(groups[i]), bb(groups[j])
                if bi[0] - gap <= bj[2] and bj[0] - gap <= bi[2] and bi[1] - gap <= bj[3] and bj[1] - gap <= bi[3]:
                    groups[i] += groups.pop(j); changed = True; break
            if changed: break
    groups = [g for g in groups if sum(x[2] * x[3] for x in g) > 2000]
    H = m.shape[0]
    groups.sort(key=lambda g: (round((bb(g)[1] + bb(g)[3]) / 2 / (H / 2)), bb(g)[0]))
    out = []
    for g in groups:
        x0, y0, x1, y1 = bb(g)
        ids = [x[4] for x in g]
        mm = np.isin(lab[y0:y1, x0:x1], ids)
        rgba = np.zeros((y1 - y0, x1 - x0, 4), np.uint8); rgba[..., :3] = a[y0:y1, x0:x1]; rgba[..., 3] = np.where(mm, 255, 0)
        out.append(rgba)
    return out

def bb(g):
    return (min(x[0] for x in g), min(x[1] for x in g), max(x[0] + x[2] for x in g), max(x[1] + x[3] for x in g))

def save(name, rgba, world_w=None, world_h=None):
    h, w = rgba.shape[:2]
    if world_w: W2 = round(world_w * 2); H2 = round(h * W2 / w)
    else: H2 = round(world_h * 2); W2 = round(w * H2 / h)
    f = rgba.astype(np.float32) / 255; pm = f.copy(); pm[..., :3] *= f[..., 3:4]
    r = cv2.resize(pm, (W2, H2), interpolation=cv2.INTER_AREA)
    al = r[..., 3:4]; rgb = np.where(al > 1e-4, r[..., :3] / np.maximum(al, 1e-4), 0)
    o = np.zeros((H2, W2, 4), np.uint8); o[..., :3] = np.clip(rgb * 255 + .5, 0, 255); o[..., 3] = np.where(al[..., 0] >= .5, 255, 0)
    Image.fromarray(o, 'RGBA').save(os.path.join(OUT, name + '.webp'), 'WEBP', lossless=True)
    return [W2 / 2, H2 / 2], o

ART = {}
if os.path.exists(ART_JS): ART = json.loads(re.search(r'= (\{.*\});', open(ART_JS).read(), re.S).group(1))
prev = []
for sheet, base, gap, size in [('path_stone.png', 'pf_path_stone', 40, dict(world_h=32)), ('path_concrete.png', 'pf_path_concrete', 25, dict(world_h=34))]:
    ps = pieces(os.path.join(SRC, sheet), gap)
    assert len(ps) == 8, f'{sheet}: found {len(ps)} pieces, want 8'
    for i, p in enumerate(ps):
        ART[f'{base}_{i + 1}'], o = save(f'{base}_{i + 1}', p, **size); prev.append(o)
for era in ('log', 'stone', 'concrete'):
    ps = pieces(os.path.join(SRC, f'bridge_{era}.png'), 60)
    assert len(ps) == 2, f'bridge_{era}: found {len(ps)} pieces'
    hz, vt = sorted(ps, key=lambda p: -p.shape[1] / p.shape[0])
    ART[f'pw_br_{era}_h'], o = save(f'pw_br_{era}_h', hz, world_w=96); prev.append(o)
    ART[f'pw_br_{era}_v'], o = save(f'pw_br_{era}_v', vt, world_h=96); prev.append(o)
open(ART_JS, 'w').write('// GENERATED by scripts/plan-map.mjs / scripts/ingest-v029.py — extra sprites (assets/v10/<name>.webp), merged into ART10 by src/maps/index.js\nexport const MAP_ART = ' + json.dumps(ART) + ';\n')
print({k: v for k, v in ART.items() if not k.startswith('map')})
if '--preview' in sys.argv:
    W = sum(o.shape[1] for o in prev) + 4 * len(prev); H = max(o.shape[0] for o in prev)
    c = Image.new('RGBA', (W, H), (60, 120, 70, 255)); x = 0
    for o in prev: c.alpha_composite(Image.fromarray(o, 'RGBA'), (x, H - o.shape[0])); x += o.shape[1] + 4
    os.makedirs(os.path.join(ROOT, 'qa'), exist_ok=True); c.save(os.path.join(ROOT, 'qa', 'v029_preview.png'))
